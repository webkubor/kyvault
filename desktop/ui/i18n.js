export const LANGS = { 'zh-CN': zh, 'en': en };

let current = DEFAULT_LANG;

export function normalizeLang(value) {
  return value === 'en' ? 'en' : DEFAULT_LANG;
}

export function getLang() {
  return current;
}

export function setLang(lang) {
  current = normalizeLang(lang);
}

export function localeTag() {
  return current;
}

export function translate(lang, key, vars) {
  const dict = LANGS[lang] || LANGS[DEFAULT_LANG];
  const raw = dict[key] ?? LANGS[DEFAULT_LANG][key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (m, name) =>
    vars[name] === undefined ? m : String(vars[name])
  );
}

// Bound to the current language for convenient rendering code.
export function t(key, vars) {
  return translate(current, key, vars);
}
