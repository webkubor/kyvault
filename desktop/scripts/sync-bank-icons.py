"""Refresh Ky's offline bank icons from a local free-imgbed checkout."""
import json
from pathlib import Path
import re
import shutil
import sys

source = Path(sys.argv[1]) / 'bank-icons'
ui = Path(__file__).resolve().parents[1] / 'ui'
dest = ui / 'icons' / 'banks'
rows = json.loads((source / 'catalog.json').read_text())
dest.mkdir(parents=True, exist_ok=True)
for row in rows:
    name = row['id']
    if not re.fullmatch('[a-z0-9-]+', name) or row['file'] != name + '.svg':
        raise ValueError('invalid bank identifier')
    shutil.copyfile(source / row['file'], dest / row['file'])
shutil.copyfile(source / 'LICENSE', dest / 'LICENSE')
shutil.copyfile(source / 'README.md', dest / 'README.md')
shutil.copyfile(source / 'catalog.json', dest / 'catalog.json')
(ui / 'bank-catalog.js').write_text('// Generated by scripts/sync-bank-icons.py from free-imgbed/bank-icons.\nexport const banks = ' + json.dumps(rows, ensure_ascii=False, indent=2) + ';\n')
